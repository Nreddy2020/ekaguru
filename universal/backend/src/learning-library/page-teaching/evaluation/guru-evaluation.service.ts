import {
  BadRequestException,
  ConflictException,
  Injectable,
  NotFoundException,
  ServiceUnavailableException,
} from "@nestjs/common";
import { PrismaService } from "../../prisma.service";
import { PageEvidenceService } from "../page-evidence.service";
import { GuruPlannerService } from "../guru-planner.service";
import { GuruModelService } from "../guru-model.service";
import { GuruGenerationQueueService } from "../guru-generation-queue.service";
import { DEPTHS } from "../guru-plan.schema";
import {
  GURU_RUBRIC,
  GURU_RUBRIC_VERSION,
  RubricScores,
  RubricVerdict,
  reconcileVerdict,
  validateScores,
  weightedScore,
} from "./guru-evaluation.rubric";

export const BUILTIN_BOOKS = [
  "evs-class-5",
  "maths-class-5",
  "science-class-6",
  "social-class-5",
];
const GRADE_BANDS = [
  "EARLY_CHILDHOOD",
  "PRIMARY",
  "MIDDLE_SCHOOL",
  "HIGH_SCHOOL",
  "ADVANCED",
];

export interface EvaluationCaseInput {
  bookId: string;
  physicalPage: number;
  subject: string;
  gradeBand: string;
  language?: string;
  depth: string;
}
export interface ReviewInput {
  scores: unknown;
  verdict?: unknown;
  notes?: string;
}

/**
 * Educator-reviewed evaluation corpus.
 * A case is one (page, depth, language). Lessons are generated by the same
 * planner learners use; educators score them against the versioned rubric.
 * The corpus is the gate that decides whether Guru checkpoints may feed mastery.
 */
@Injectable()
export class GuruEvaluationService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly evidence: PageEvidenceService,
    private readonly planner: GuruPlannerService,
    private readonly model: GuruModelService,
    private readonly queue: GuruGenerationQueueService,
  ) {}

  get minimumPassedCases() {
    const raw = Number(process.env.GURU_EVAL_MIN_PASSED_CASES);
    return Number.isFinite(raw) && raw >= 1 ? Math.floor(raw) : 20;
  }
  rubric() {
    return {
      version: GURU_RUBRIC_VERSION,
      criteria: GURU_RUBRIC,
      passMinimum: 3,
      scoreRange: [0, 4],
      consensusRule:
        "A case counts as passed when every review at the current rubric version has verdict PASS and at least one review exists.",
      minimumPassedCases: this.minimumPassedCases,
    };
  }

  private normalise(input: EvaluationCaseInput) {
    if (
      typeof input?.bookId !== "string" ||
      !/^[A-Za-z0-9_-]{1,120}$/.test(input.bookId)
    )
      throw new BadRequestException("Invalid bookId");
    if (
      !Number.isInteger(input.physicalPage) ||
      input.physicalPage < 1 ||
      input.physicalPage > 10000
    )
      throw new BadRequestException("Invalid physical page");
    if (
      typeof input.subject !== "string" ||
      !input.subject.trim() ||
      input.subject.length > 120
    )
      throw new BadRequestException("Invalid subject");
    if (!GRADE_BANDS.includes(input.gradeBand))
      throw new BadRequestException("Invalid grade band");
    if (!(DEPTHS as readonly string[]).includes(input.depth))
      throw new BadRequestException("Invalid depth");
    const language = (input.language || "en").trim();
    if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(language))
      throw new BadRequestException("Invalid language");
    return {
      bookId: input.bookId,
      physicalPage: input.physicalPage,
      subject: input.subject.trim(),
      gradeBand: input.gradeBand as any,
      language,
      depth: input.depth,
    };
  }

  async createCase(input: EvaluationCaseInput, userId: string) {
    const data = this.normalise(input);
    try {
      return await this.prisma.guruEvaluationCase.create({
        data: { ...data, createdBy: userId },
      });
    } catch (error: any) {
      if (error?.code === "P2002")
        throw new ConflictException("This page, depth and language already has a case.");
      throw error;
    }
  }

  /** Bulk import of a manifest; duplicates are skipped, invalid rows fail the whole import. */
  async importCases(list: EvaluationCaseInput[], userId: string) {
    if (!Array.isArray(list) || !list.length || list.length > 2000)
      throw new BadRequestException("Provide between 1 and 2000 cases");
    const rows = list.map((c) => ({ ...this.normalise(c), createdBy: userId }));
    const result = await this.prisma.guruEvaluationCase.createMany({
      data: rows,
      skipDuplicates: true,
    });
    return { created: result.count, skipped: rows.length - result.count };
  }

  async listCases(filter: { subject?: string; depth?: string } = {}) {
    const cases = await this.prisma.guruEvaluationCase.findMany({
      where: {
        ...(filter.subject ? { subject: filter.subject } : {}),
        ...(filter.depth ? { depth: filter.depth } : {}),
      },
      include: { reviews: true },
      orderBy: [{ subject: "asc" }, { bookId: "asc" }, { physicalPage: "asc" }],
    });
    return cases.map((c) => this.summariseCase(c));
  }

  private summariseCase(c: any) {
    const current = (c.reviews || []).filter(
      (r: any) => r.rubricVersion === GURU_RUBRIC_VERSION,
    );
    const consensus: RubricVerdict | "UNREVIEWED" = !current.length
      ? "UNREVIEWED"
      : current.every((r: any) => r.verdict === "PASS")
        ? "PASS"
        : current.some((r: any) => r.verdict === "FAIL")
          ? "FAIL"
          : "REVISE";
    return {
      id: c.id,
      bookId: c.bookId,
      physicalPage: c.physicalPage,
      sourceHash: c.sourceHash,
      subject: c.subject,
      gradeBand: c.gradeBand,
      language: c.language,
      depth: c.depth,
      artifactId: c.artifactId,
      prepared: Boolean(c.artifactId),
      reviewCount: current.length,
      consensus,
      meanWeightedScore: current.length
        ? Number(
            (
              current.reduce(
                (sum: number, r: any) => sum + weightedScore(r.scores),
                0,
              ) / current.length
            ).toFixed(4),
          )
        : null,
    };
  }

  private async load(caseId: string) {
    const record = await this.prisma.guruEvaluationCase.findUnique({
      where: { id: caseId },
      include: { reviews: true, artifact: true },
    });
    if (!record) throw new NotFoundException("Evaluation case unavailable");
    return record;
  }

  /** Generate the lesson educators will review, using the learner-facing planner. */
  async prepare(caseId: string, userId: string) {
    const record = await this.load(caseId);
    if (!this.model.configured)
      throw new ServiceUnavailableException(
        "Configure the Guru provider API key and GURU_MODEL before preparing evaluation lessons.",
      );
    const source = BUILTIN_BOOKS.includes(record.bookId)
      ? await this.evidence.builtin(record.bookId, String(record.physicalPage))
      : await this.evidence.material(record.bookId, String(record.physicalPage));
    const payload: any = await this.planner.build(
      source,
      { depth: record.depth as any, language: record.language },
      async () => {
        /* evaluation generation is curator work; no learner budget applies */
      },
    );
    await this.prisma.guruEvaluationCase.update({
      where: { id: caseId },
      data: { artifactId: payload.plan.id, sourceHash: source.sourceHash },
    });
    return {
      caseId,
      artifactId: payload.plan.id,
      sourceHash: source.sourceHash,
      preparedBy: userId,
    };
  }

  /** HTTP preparation never blocks on the model: it queues (or reuses) a durable job. */
  async enqueuePrepare(caseId: string, user: any) {
    const record = await this.load(caseId);
    if (!this.model.configured)
      throw new ServiceUnavailableException(
        "Configure the Guru provider API key and GURU_MODEL before preparing evaluation lessons.",
      );
    const source = BUILTIN_BOOKS.includes(record.bookId)
      ? await this.evidence.builtin(record.bookId, String(record.physicalPage))
      : await this.evidence.material(record.bookId, String(record.physicalPage));
    const job = await this.queue.enqueue(
      source,
      { depth: record.depth as any, language: record.language },
      user,
    );
    if (job.status === "DONE")
      await this.prisma.guruEvaluationCase.update({
        where: { id: caseId },
        data: { artifactId: job.artifactId, sourceHash: source.sourceHash },
      });
    return { caseId, job };
  }

  /** Everything a reviewer needs, including server-held rubrics (reviewers are curators). */
  async packet(caseId: string, includeImage = false) {
    const record = await this.load(caseId);
    const payload: any = record.artifact?.payload || null;
    let image: string | null = null;
    if (includeImage) {
      const source = BUILTIN_BOOKS.includes(record.bookId)
        ? await this.evidence.builtin(record.bookId, String(record.physicalPage))
        : await this.evidence.material(record.bookId, String(record.physicalPage));
      image = source.imageDataUrl;
    }
    return {
      case: this.summariseCase(record),
      rubric: this.rubric(),
      lesson: payload?.plan || null,
      page: payload?.page
        ? { ...payload.page, imageDataUrl: image }
        : image
          ? { imageDataUrl: image }
          : null,
      audit: payload?.audit || null,
      reviews: record.reviews.map((r) => ({
        id: r.id,
        reviewerId: r.reviewerId,
        rubricVersion: r.rubricVersion,
        scores: r.scores,
        verdict: r.verdict,
        notes: r.notes,
        createdAt: r.createdAt,
      })),
    };
  }

  async packetMarkdown(caseId: string) {
    const packet = await this.packet(caseId);
    const lines: string[] = [];
    lines.push("# Guru evaluation packet");
    lines.push("");
    lines.push(
      "Case " +
        packet.case.id +
        " · " +
        packet.case.bookId +
        " physical page " +
        packet.case.physicalPage +
        " · " +
        packet.case.subject +
        " · " +
        packet.case.gradeBand +
        " · depth " +
        packet.case.depth +
        " · language " +
        packet.case.language,
    );
    lines.push(
      "Source hash: " + (packet.case.sourceHash || "not prepared") +
        " · Lesson artifact: " + (packet.case.artifactId || "not prepared"),
    );
    lines.push("");
    lines.push("## Rubric v" + packet.rubric.version + " (score 0-4, pass at 3)");
    for (const c of packet.rubric.criteria)
      lines.push("- **" + c.title + "** (" + c.id + (c.gate ? ", gate" : "") + "): " + c.question);
    lines.push("");
    if (!packet.lesson) {
      lines.push("_Lesson not yet prepared. Run prepare with a configured provider._");
    } else {
      lines.push("## Objectives");
      for (const o of packet.lesson.objectives || []) lines.push("- " + o);
      lines.push("");
      lines.push("## Actions");
      (packet.lesson.actions || []).forEach((a: any, i: number) => {
        lines.push(
          (i + 1) + ". [" + a.kind + "] " + a.text + "  \n   Speech: " + a.speech +
            "  \n   Evidence: " + (a.evidenceIds || []).join(", "),
        );
        if (a.scene)
          lines.push(
            "   Scene: " + a.scene.map((s: any) => s.type + "@" + s.x + "," + s.y + (s.text ? " '" + s.text + "'" : "")).join("; "),
          );
        if (a.rubric)
          lines.push(
            "   Expected: " + a.rubric.expected + "  \n   Criteria: " + a.rubric.criteria.join(" | ") +
              "  \n   Hint: " + a.rubric.hint + "  \n   Misconception: " + a.rubric.misconception,
          );
      });
      lines.push("");
      lines.push("## Omitted blocks (model-stated reasons)");
      if (!(packet.lesson.omitted || []).length) lines.push("_None._");
      for (const o of packet.lesson.omitted || []) lines.push("- " + o.evidenceId + ": " + o.reason);
      lines.push("");
      lines.push("## Uncertain regions set aside (not taught; confidence below 80%)");
      if (!(packet.page?.uncertain || []).length) lines.push("_None._");
      for (const u of packet.page?.uncertain || [])
        lines.push("- " + u.blockId + " [" + Math.round((u.confidence || 0) * 100) + "%]: " + u.text);
      lines.push("");
      lines.push("## Source blocks");
      for (const b of packet.page?.blocks || [])
        lines.push("- " + b.blockId + " [" + b.type + ", " + Math.round((b.confidence || 0) * 100) + "%]: " + b.text);
    }
    lines.push("");
    lines.push("## Existing reviews");
    if (!packet.reviews.length) lines.push("_None yet._");
    for (const r of packet.reviews)
      lines.push(
        "- " + r.reviewerId + " · v" + r.rubricVersion + " · " + r.verdict + " · " + JSON.stringify(r.scores) + (r.notes ? " · " + r.notes : ""),
      );
    return lines.join("\n") + "\n";
  }

  async review(caseId: string, reviewerId: string, input: ReviewInput) {
    const record = await this.load(caseId);
    if (!record.artifactId)
      throw new BadRequestException(
        "Prepare the lesson before reviewing it; scores must refer to a real generated lesson.",
      );
    const scores: RubricScores = validateScores(input.scores);
    const verdict = reconcileVerdict(input.verdict, scores);
    const notes =
      typeof input.notes === "string" ? input.notes.trim().slice(0, 4000) : null;
    const review = await this.prisma.guruEvaluationReview.upsert({
      where: {
        caseId_reviewerId_rubricVersion: {
          caseId,
          reviewerId,
          rubricVersion: GURU_RUBRIC_VERSION,
        },
      },
      create: {
        caseId,
        reviewerId,
        rubricVersion: GURU_RUBRIC_VERSION,
        scores,
        verdict,
        notes,
      },
      update: { scores, verdict, notes },
    });
    return { ...review, weightedScore: weightedScore(scores) };
  }

  async summary() {
    const cases = await this.listCases();
    const groups = new Map<string, any>();
    for (const c of cases) {
      const key = c.subject + "|" + c.depth + "|" + c.language;
      const g = groups.get(key) || {
        subject: c.subject,
        depth: c.depth,
        language: c.language,
        cases: 0,
        prepared: 0,
        reviewed: 0,
        passed: 0,
        failed: 0,
      };
      g.cases++;
      if (c.prepared) g.prepared++;
      if (c.consensus !== "UNREVIEWED") g.reviewed++;
      if (c.consensus === "PASS") g.passed++;
      if (c.consensus === "FAIL") g.failed++;
      groups.set(key, g);
    }
    const byDepth = new Map<string, number>();
    for (const c of cases)
      if (c.consensus === "PASS")
        byDepth.set(
          c.depth + "|" + c.language,
          (byDepth.get(c.depth + "|" + c.language) || 0) + 1,
        );
    return {
      rubricVersion: GURU_RUBRIC_VERSION,
      minimumPassedCases: this.minimumPassedCases,
      totalCases: cases.length,
      groups: [...groups.values()],
      approvedDepths: [...byDepth.entries()]
        .filter(([, n]) => n >= this.minimumPassedCases)
        .map(([key, passed]) => {
          const [depth, language] = key.split("|");
          return { depth, language, passed };
        }),
    };
  }

  /** Gate consumed by the mastery bridge. */
  async isDepthApproved(depth: string, language: string): Promise<boolean> {
    const cases = await this.prisma.guruEvaluationCase.findMany({
      where: { depth, language },
      include: { reviews: { where: { rubricVersion: GURU_RUBRIC_VERSION } } },
    });
    const passed = cases.filter(
      (c) => c.reviews.length && c.reviews.every((r) => r.verdict === "PASS"),
    ).length;
    return passed >= this.minimumPassedCases;
  }
}
